import 'package:flutter/widgets.dart';
import 'home_guide_tour_overlay.dart';

enum HomeGuideTarget {
  play,
  campaign,
  modes,
  friends,
  store,
  support,
  menu,
  character,
  level,
  coins,
  gems,
  keys,
  tickets,
  offer,
  guide,
}

/// Short speech turns, with one idea per bubble and the real economy rules.
List<GuideStep> buildHomeGuideSteps(Map<HomeGuideTarget, GlobalKey> targets,
    {required bool showOffer}) {
  GuideStep step(
          HomeGuideTarget target, String chapter, String title, String text) =>
      GuideStep(
          targetKey: targets[target],
          chapter: chapter,
          title: title,
          text: text);
  return [
    const GuideStep(
        chapter: 'أهلًا بك',
        title: 'أهلًا في الساحة',
        text:
            'سأشرح لك الأزرار خطوة بخطوة. اضغط «التالي» للمتابعة، أو اضغط فقاعة الكلام لإظهار النص كاملًا.'),
    step(HomeGuideTarget.play, 'طرق اللعب', 'اختر مواجهتك',
        'من «العب» تتحدى لاعبًا آخر. اختر عدد العملات التي تدخل بها المباراة، ثم اختر منافسك أو ابحث عن منافس عشوائي.'),
    step(HomeGuideTarget.play, 'طرق اللعب', 'ابدأ على راحتك',
        'اختر مبلغ «صفر» للعب دون دفع عملات. للمواجهة عبر الإنترنت، سجّل الدخول وتأكد من اتصالك بالشبكة.'),
    step(HomeGuideTarget.campaign, 'طرق اللعب', 'تحدي المراحل',
        'ابدأ من مرحلة مفتوحة، وأجب عن الأسئلة لتحقيق هدفها. الفوز يفتح المرحلة التالية ويمنحك نجومًا.'),
    step(HomeGuideTarget.modes, 'طرق اللعب', 'أوضاع اللعب',
        'هنا تختار نوع اللعب: فريقان على جهاز واحد، أو غرفة جماعية، أو تحدي صديق، أو لعب دون إنترنت.'),
    step(HomeGuideTarget.friends, 'تواصل وتنافس', 'الأصدقاء واللاعبون',
        'أضف صديقك برمز الصداقة، ثم أرسل له دعوة تحدٍّ. وتجد هنا دعوات اللاعبين التي وصلتك.'),
    step(HomeGuideTarget.coins, 'افهم أرصدتك', 'العملات الذهبية',
        'هذه عملاتك الذهبية. تستخدمها لدخول مواجهات بعملات، ولشراء العناصر المسعّرة بالعملات. اضغط الرصيد لفتح المتجر.'),
    step(HomeGuideTarget.gems, 'افهم أرصدتك', 'الجواهر',
        'بالجواهر تشتري الشخصيات والتصنيفات وأرصدة اللعب المسعّرة بالجواهر. ويمكنك تحويلها إلى عملات في المتجر.'),
    step(HomeGuideTarget.keys, 'افهم أرصدتك', 'مفتاح دخول التحدي',
        'دخول مباراة كاملة في «التحدي الرئيسي» يحتاج مفتاحًا واحدًا. الرقم هنا هو مجموع المفاتيح المتاحة لك.'),
    step(HomeGuideTarget.keys, 'افهم أرصدتك', 'مفاتيحك اليومية',
        'لديك ٣ مفاتيح يومية. يعود رصيدها إلى ٣ كل يوم، وتستخدمها اللعبة قبل المفاتيح الإضافية.'),
    step(HomeGuideTarget.keys, 'افهم أرصدتك', 'ما المفاتيح الإضافية؟',
        'تحصل عليها من المتجر والمكافآت. تستخدمها بعد نفاد المفاتيح اليومية، وما يتبقى منها ينتقل لليوم التالي.'),
    step(HomeGuideTarget.tickets, 'افهم أرصدتك', 'تذاكر التصنيفات',
        'بكل تذكرة تجرّب تصنيف أسئلة مقفلًا لمباراة واحدة. التصنيفات المفتوحة أو التي اشتريتها لا تحتاج تذاكر.'),
    step(HomeGuideTarget.campaign, 'افهم أرصدتك', 'قلوب المراحل',
        'القلب هو محاولة في «تحدي المراحل». يُحجز قلب عند البدء؛ يعود إليك إذا فزت، ويُستهلك إذا خسرت.'),
    step(HomeGuideTarget.campaign, 'افهم أرصدتك', 'حافظ على محاولاتك',
        'لديك ٣ قلوب يومية تتجدد كل يوم. القلوب التي تحصل عليها من المتجر أو المكافآت لا تختفي مع التجدد.'),
    step(HomeGuideTarget.store, 'جهّز رحلتك', 'المتجر',
        'اشترِ الشخصيات والتصنيفات، واشحن العملات والجواهر وأرصدة اللعب. اقرأ محتوى العنصر وسعره قبل الشراء.'),
    if (showOffer)
      step(HomeGuideTarget.offer, 'جهّز رحلتك', 'العرض الخاص',
          'اضغط لترى محتويات العرض وسعره ووقت انتهائه، ثم قرّر إن كنت تريد شراءه.'),
    step(HomeGuideTarget.character, 'هويتك في الساحة', 'اختر شخصيتك',
        'اضغط شخصيتك لتغيير مظهرك. اختر شخصية مفتوحة، أو اطّلع على سعر الشخصية المقفلة وشرط فتحها.'),
    step(HomeGuideTarget.level, 'هويتك في الساحة', 'المستوى والخبرة',
        'هذا مستواك، والشريط يوضح تقدمك للمستوى التالي. تحصل على الخبرة من اللعب؛ الخبرة لا تُنفق في المتجر.'),
    step(HomeGuideTarget.menu, 'كل أدواتك', 'حسابك ومكافآتك',
        'افتح القائمة للوصول إلى ملفك، والمتصدرين، ودولاب الحظ. النقطة المضيئة تنبّهك إلى لفة مجانية متاحة.'),
    step(HomeGuideTarget.menu, 'كل أدواتك', 'تابع إنجازاتك',
        '«الإحصائيات» لنتائج لعبك، و«الإنجازات» للأهداف ومكافآتها. افتح «الإعدادات» لضبط اللعبة والحساب.'),
    step(HomeGuideTarget.support, 'نحن معك', 'تواصل معنا',
        'اضغط هنا لإرسال مشكلة أو اقتراح إلى فريق الدعم. اكتب ما حدث، وفي أي شاشة حدث.'),
    step(HomeGuideTarget.guide, 'نحن معك', 'مرشد الساحة',
        'أعد شرح الساحة من هذا الزر. وستجد زر «شرح الصفحة» داخل الأوضاع وتحدي المراحل والمتجر.'),
    const GuideStep(
        chapter: 'أنت جاهز',
        title: 'جاهز للتحدي؟',
        text:
            'جرّب التحدي دون حساب، أو سجّل الدخول لحفظ تقدمك. اختر «استكشف الساحة» إذا أردت متابعة الاستكشاف.',
        isFinalChoiceStep: true),
  ];
}
