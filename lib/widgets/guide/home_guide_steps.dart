import 'package:flutter/widgets.dart';
import 'home_guide_tour_overlay.dart';

enum HomeGuideTarget {
  play,
  campaign,
  modes,
  friends,
  store,
  support,
  menu,
  character,
  level,
  coins,
  gems,
  keys,
  tickets,
  offer,
  guide,
}

/// Short speech turns, with one idea per bubble and the real economy rules.
List<GuideStep> buildHomeGuideSteps(Map<HomeGuideTarget, GlobalKey> targets,
    {required bool showOffer}) {
  GuideStep step(
          HomeGuideTarget target, String chapter, String title, String text) =>
      GuideStep(
          targetKey: targets[target],
          chapter: chapter,
          title: title,
          text: text);
  return [
    const GuideStep(
        chapter: 'أهلًا بك',
        title: 'أهلًا في الساحة',
        text:
            'أنا مرشدك! اضغط فقاعة الكلام لإظهار الجملة كاملة، و«التالي» للمتابعة. يمكنك إعادة الجولة لاحقًا من زر المرشد.'),
    step(HomeGuideTarget.play, 'طرق اللعب', 'اختر مواجهتك',
        'زر «العب» يتيح لك اختيار مبلغ المباراة من العملات، ثم البحث عن منافس عشوائي أو اختيار لاعب من الساحة.'),
    step(HomeGuideTarget.play, 'طرق اللعب', 'ابدأ على راحتك',
        'اختر مبلغ صفر للتدريب دون دفع عملات. تحتاج المواجهات عبر الإنترنت إلى تسجيل الدخول والاتصال بالشبكة.'),
    step(HomeGuideTarget.campaign, 'طرق اللعب', 'تحدي المراحل',
        'هنا تبدأ المغامرة! اختر مرحلة متاحة، وأجب عن الأسئلة لتجمع النجوم وتفتح المراحل التالية.'),
    step(HomeGuideTarget.modes, 'طرق اللعب', 'أوضاع اللعب',
        'اختر التحدي الرئيسي، أو ادخل غرفة جماعية، أو تحدَّ أصدقاءك. وستجد أيضًا وضعًا للتدريب دون إنترنت.'),
    step(HomeGuideTarget.friends, 'تواصل وتنافس', 'الأصدقاء واللاعبون',
        'تعرّف على اللاعبين، وأضف أصدقاءك برمز الصداقة. من هنا ترسل دعوات التحدي وتقبل الدعوات الواردة.'),
    step(HomeGuideTarget.coins, 'افهم أرصدتك', 'العملات الذهبية',
        'تستخدم العملات في مبالغ المواجهات وشراء العناصر التي تحمل سعرًا بالعملات. اجمعها من اللعب والمكافآت، واضغط الرصيد لفتح المتجر.'),
    step(HomeGuideTarget.gems, 'افهم أرصدتك', 'الجواهر',
        'الجواهر رصيد آخر لشراء الشخصيات والموارد والعروض التي تحمل سعرًا بالجواهر. ويمكنك تحويلها إلى عملات من المتجر.'),
    step(HomeGuideTarget.keys, 'افهم أرصدتك', 'مفتاح دخول التحدي',
        'تحتاج مفتاحًا لدخول مباراة كاملة في التحدي الرئيسي. هذا الرصيد يجمع مفاتيحك اليومية والإضافية.'),
    step(HomeGuideTarget.keys, 'افهم أرصدتك', 'مفاتيحك اليومية',
        'تُستخدم المفاتيح اليومية أولًا وتتجدد عند إعادة الضبط. أما المفاتيح الإضافية فتبقى محفوظة حتى تستخدمها.'),
    step(HomeGuideTarget.tickets, 'افهم أرصدتك', 'تذاكر التصنيفات',
        'التذكرة تفتح تصنيف أسئلة مقفلًا لمباراة واحدة فقط. لا تحتاج تذكرة للتصنيفات المتاحة لك أو التي تملكها.'),
    step(HomeGuideTarget.campaign, 'افهم أرصدتك', 'قلوب المراحل',
        'القلوب لمحاولات تحدي المراحل. يُحجز قلب عند بدء المحاولة، ويُعاد إليك عند الفوز. تجد رصيد القلوب داخل الخريطة والمتجر.'),
    step(HomeGuideTarget.campaign, 'افهم أرصدتك', 'حافظ على محاولاتك',
        'تُستخدم القلوب اليومية أولًا وتتجدد عند إعادة الضبط. وتبقى القلوب الإضافية محفوظة، مثل المفاتيح الإضافية.'),
    step(HomeGuideTarget.store, 'جهّز رحلتك', 'المتجر',
        'تجد هنا الشخصيات والتصنيفات والأرصدة وموارد اللعب. افتح أي عنصر لتعرف محتواه وسعره قبل تأكيد الشراء.'),
    if (showOffer)
      step(HomeGuideTarget.offer, 'جهّز رحلتك', 'العرض الخاص',
          'اضغط لعرض مزايا العرض وسعره ومدته. يمكنك قراءة التفاصيل ثم اختيار الشراء إذا ناسبك العرض.'),
    step(HomeGuideTarget.character, 'هويتك في الساحة', 'اختر شخصيتك',
        'هذه شخصيتك الحالية. اضغط عليها لاستعراض الشخصيات واختيار ما فتحته منها. ستجد شرط فتح كل شخصية أو سعرها بجوارها.'),
    step(HomeGuideTarget.level, 'هويتك في الساحة', 'المستوى والخبرة',
        'الشارة تعرض مستواك، والشريط يوضح خبرتك نحو المستوى التالي. الخبرة تقيس تقدمك، ولا تُستخدم لشراء العناصر.'),
    step(HomeGuideTarget.menu, 'كل أدواتك', 'حسابك ومكافآتك',
        'من القائمة تفتح ملفك الشخصي، وتطّلع على المتصدرين، وتستلم مكافأتك اليومية. علامة التنبيه تعني وجود ما يستحق المراجعة.'),
    step(HomeGuideTarget.menu, 'كل أدواتك', 'تابع إنجازاتك',
        'الإحصائيات تعرض نتائجك، والإنجازات تعرض أهدافك ومكافآتها. ومن الإعدادات تضبط خيارات اللعبة والحساب.'),
    step(HomeGuideTarget.support, 'نحن معك', 'تواصل معنا',
        'إذا واجهت مشكلة أو لديك اقتراح، اضغط هنا للتواصل مع فريق الدعم. اذكر ما حدث حتى نتمكن من مساعدتك.'),
    step(HomeGuideTarget.guide, 'نحن معك', 'مرشد الساحة',
        'ستجدني هنا كلما احتجت! أعد الجولة، أو جرّب التحدي المجاني، أو افتح خيارات تسجيل الدخول من هذا الزر.'),
    const GuideStep(
        chapter: 'أنت جاهز',
        title: 'جاهز للتحدي؟',
        text:
            'جرّب تحديًا مجانيًا دون حساب، أو سجّل الدخول لحفظ تقدمك والمنافسة. ويمكنك استكشاف الساحة الآن والعودة إليّ لاحقًا.',
        isFinalChoiceStep: true),
  ];
}
