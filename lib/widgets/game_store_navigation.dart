  const GameStoreNavIcon({super.key, required this.index, this.size = 44});
  final int index;
  final double size;

  @override
  Widget build(BuildContext context) {
    final source = _navigationIconRects[index]!;
    return SizedBox(
        width: size,
        height: size,
        child: FittedBox(
            fit: BoxFit.contain,
            child: SizedBox(
                width: source.width * 3168,
                height: source.height * 568,
                child: ClipPath(
                    clipper: _NavigationIconClipper(index),
                    child: _NavigationSlice(source)))));
  }
}

class _NavigationIconClipper extends CustomClipper<Path> {
  const _NavigationIconClipper(this.index);
  final int index;

  @override
  Path getClip(Size size) {
    final path = Path();
    for (final contour in _navigationContours[index]!) {
      path.addPolygon(
          contour
              .map((point) =>
                  Offset(point.dx * size.width, point.dy * size.height))
              .toList(),
          true);
    }
    return path;
  }

  @override
  bool shouldReclip(_NavigationIconClipper oldClipper) =>
      oldClipper.index != index;
}

