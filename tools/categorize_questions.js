// Arabic normalisation: strip tashkeel/tatweel, unify alef/yaa/taa-marbuta.
function normalize(s) {
  if (!s) return "";
  return String(s)
    .replace(/[ً-ْـ]/g, "") // harakat + tatweel
    .replace(/[آأإٱ]/g, "ا") // آأإٱ -> ا
    .replace(/ى/g, "ي") // ى -> ي
    .replace(/ة/g, "ه") // ة -> ه
    .replace(/ؤ/g, "و") // ؤ -> و
    .replace(/ئ/g, "ي") // ئ -> ي
    .toLowerCase();
}

