const PREP = CATEGORIES.map(([name, words]) => [name, words.map(normalize)]);

function classify(record) {
  const hay = normalize(
    [record.Q, record.R, record.W1, record.W2, record.W3].filter(Boolean).join(" ")
  );
  for (const [name, words] of PREP) {
    for (const w of words) {
      if (w && hay.indexOf(w) !== -1) return name;
    }
  }
  return FALLBACK;
}

function processFile(file) {
  if (!fs.existsSync(file)) {
    console.log("skip (missing): " + file);
    return;
  }
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const counts = {};
  const out = data.map((q) => {
    const category = classify(q);
    counts[category] = (counts[category] || 0) + 1;
    return {
      Level: q.Level,
      Q: q.Q,
      R: q.R,
      W1: q.W1,
      W2: q.W2,
      W3: q.W3,
      Category: category,
    };
  });
  fs.writeFileSync(file, JSON.stringify(out, null, 2) + "\n", "utf8");
  console.log("\n" + file + "  (" + out.length + " questions)");
  Object.keys(counts)
    .sort((a, b) => counts[b] - counts[a])
    .forEach((c) => console.log("  " + counts[c].toString().padStart(5) + "  " + c));
}

