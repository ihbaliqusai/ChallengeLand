"use strict";
// Run after changing the shared quantity vocabulary; no runtime asset loading is
// needed by Android. Keep the generated source in version control.
const fs = require("node:fs"), path = require("node:path");
const vocabulary = require("../functions/src/answer_quantity_words.json");
const fold = word => word.replace(/[\u064b-\u0652\u0670\u0640]/g, "").replace(/[أإآٱ]/g, "ا")
  .replace(/ة/g, "ه").replace(/ى/g, "ي").replace(/ؤ/g, "و").replace(/ئ/g, "ي");
const target = path.join(__dirname, "../android/app/src/main/java/com/Qi7bali/challengeland/AnswerQuantityVocabulary.java");
const lines = [
  "// Generated by tools/sync_answer_quantity_vocabulary.cjs. Edit answer_quantity_words.json.",
  "package com.qi7bali.landchallengeonline;", "", "import java.util.HashMap;", "import java.util.Map;", "",
  "final class AnswerQuantityVocabulary {", "    private AnswerQuantityVocabulary() {}",
];
for (const group of ["small", "hundreds", "scales", "units", "expand", "unitPhrases"]) {
  lines.push(`    static final Map<String, String> ${group.toUpperCase()} = new HashMap<>();`);
}
lines.push(`    static final String QUALIFIERS = ${JSON.stringify(fold(vocabulary.qualifiers))};`, "    static {");
for (const group of ["small", "hundreds", "scales", "units"]) {
  for (const [value, words] of Object.entries(vocabulary[group])) {
    lines.push(`        for (String word : ${JSON.stringify(fold(words))}.split(" ")) ${group.toUpperCase()}.put(word, ${JSON.stringify(value)});`);
  }
}
for (const [word, expansion] of Object.entries(vocabulary.expand)) lines.push(`        EXPAND.put(${JSON.stringify(fold(word))}, ${JSON.stringify(fold(expansion))});`);
for (const [phrase, unit] of Object.entries(vocabulary.unitPhrases)) lines.push(`        UNITPHRASES.put(${JSON.stringify(fold(phrase))}, ${JSON.stringify(unit)});`);
lines.push("    }", "}", "");
const source = lines.join("\n");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== source) throw new Error("Android quantity vocabulary is out of date; run node tools/sync_answer_quantity_vocabulary.cjs");
  console.log("Android and server quantity vocabulary match.");
} else fs.writeFileSync(target, source);
