void main() {
  print("Total questions created: ${turkishSeriesQuestions.length}");

  final countsByLevel = <String, int>{};
  for (final q in turkishSeriesQuestions) {
    final lvl = q['Level']!;
    countsByLevel[lvl] = (countsByLevel[lvl] ?? 0) + 1;
  }

  print("Counts by level:");
  countsByLevel.keys.toList()..sort()..forEach((k) {
    print("  Level $k: ${countsByLevel[k]}");
  });

  final tier0 = (countsByLevel['0'] ?? 0) + (countsByLevel['1'] ?? 0) + (countsByLevel['2'] ?? 0);
  final tier1 = (countsByLevel['4'] ?? 0) + (countsByLevel['5'] ?? 0) + (countsByLevel['6'] ?? 0);
  final tier2 = (countsByLevel['3'] ?? 0) + (countsByLevel['7'] ?? 0) + (countsByLevel['8'] ?? 0);

  print("Tier 0 total: $tier0 (expected 100)");
  print("Tier 1 total: $tier1 (expected 100)");
  print("Tier 2 total: $tier2 (expected 100)");

  // Assert exact counts
  final expectedLevels = {
    '0': 34,
    '1': 33,
    '2': 33,
    '4': 33,
    '5': 33,
    '6': 34,
    '3': 33,
    '7': 33,
    '8': 34,
  };

  expectedLevels.forEach((lvl, exp) {
    final actual = countsByLevel[lvl] ?? 0;
    if (actual != exp) {
      throw Exception("Level $lvl has $actual questions, expected $exp");
    }
  });

  // Verify quality
  final seenQ = <String>{};
  int leakCount = 0;
  for (int i = 0; i < turkishSeriesQuestions.length; i++) {
    final item = turkishSeriesQuestions[i];
    final q = item['Q']!;
    final r = item['R']!;
    final w1 = item['W1']!;
    final w2 = item['W2']!;
    final w3 = item['W3']!;

    if (!q.endsWith('؟')) {
      throw Exception("Question #$i does not end with '؟': $q");
    }

    if (seenQ.contains(q)) {
      throw Exception("Duplicate question at #$i: $q");
    }
    seenQ.add(q);

    final set = {r, w1, w2, w3};
    if (set.length != 4) {
      throw Exception("Duplicate options in #$i: $set");
    }

    // Check leaks
    final rNorm = r.trim().toLowerCase();
    final qNorm = q.trim().toLowerCase();
    if (rNorm.length > 3 && qNorm.contains(rNorm)) {
      print("Potential leak in #$i: Q='$q' contains R='$r'");
      leakCount++;
    }

    // Check forbidden phrases
    if (q.contains("اختر ") || q.contains("اكتب الرقم")) {
      throw Exception("Forbidden phrase in #$i: $q");
    }
  }

  print("Total distinct questions: ${seenQ.length}");
  print("Potential leaks: $leakCount");

  if (leakCount > 0) {
    throw Exception("Leaks found! Fix them before proceeding.");
  }

  // Save to file
  final jsonString = JsonEncoder.withIndent("  ").convert(turkishSeriesQuestions);
  final outFile = File('assets/questions_turkish_series_300.json');
  outFile.writeAsStringSync(jsonString, encoding: utf8);
  print("Successfully saved 300 questions to assets/questions_turkish_series_300.json");
}
