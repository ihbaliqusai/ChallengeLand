// Generates the Android/Flutter bridge from one list of canonical APK resources.
// Originals under assets/ remain editable sources, but are not shipped twice.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, 'shared_assets.json'), 'utf8'));
if (process.argv.includes('--sync-manifest')) {
  const file = path.join(root, 'pubspec.yaml');
  const seen = new Set();
  let yaml = fs.readFileSync(file, 'utf8');
  yaml = yaml.replace(/^    - (assets\/[^\r\n]+)\r?$/gm, (line, asset) => {
    const entries = asset.endsWith('/')
      ? fs.readdirSync(path.join(root, asset), {withFileTypes: true})
          .filter(entry => entry.isFile()).map(entry => asset + entry.name)
      : [asset];
    return entries.filter(entry => !manifest[entry] && !seen.has(entry) && seen.add(entry))
      .map(entry => '    - ' + entry).join('\n');
  });
  fs.writeFileSync(file, yaml.replace(/\n{3,}/g, '\n\n'));
}
const dart = `// Generated by tools/prepare_shared_assets.cjs.\nconst sharedAndroidAssets = <String, String>{\n${Object.entries(manifest).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n')}\n};\n`;
const cases = Object.entries(manifest).map(([key, source]) => {
  const resource = source.match(/\/res\/(drawable|font|raw)\/([^/.]+)\./);
  const expression = resource
    ? `context.getResources().openRawResource(R.${resource[1]}.${resource[2]})`
    : `context.getAssets().open(${JSON.stringify(source.split('/src/main/assets/')[1])})`;
  return `            case ${JSON.stringify(key)}: return ${expression};`;
}).join('\n');
const java = `// Generated by tools/prepare_shared_assets.cjs.\npackage com.qi7bali.landchallengeonline;\n\nimport android.content.Context;\nimport java.io.InputStream;\nimport java.io.IOException;\nimport java.io.ByteArrayOutputStream;\n\nfinal class SharedAssetStore {\n    private static InputStream open(Context context, String key) throws IOException {\n        switch (key) {\n${cases}\n            default: throw new IOException("Unknown shared asset: " + key);\n        }\n    }\n\n    static byte[] read(Context context, String key) throws IOException {\n        try (InputStream input = open(context, key);\n             ByteArrayOutputStream output = new ByteArrayOutputStream()) {\n            byte[] buffer = new byte[16384];\n            int count;\n            while ((count = input.read(buffer)) != -1) output.write(buffer, 0, count);\n            return output.toByteArray();\n        }\n    }\n}\n`;
for (const [file, content] of [
  ['lib/core/shared_android_assets.g.dart', dart],
  ['android/app/src/main/java/com/Qi7bali/challengeland/SharedAssetStore.java', java],
]) {
  const target = path.join(root, file);
  if (process.argv.includes('--check')) {
    // dart format may normalize quotes/line wrapping in generated Dart.
    const normalize = s => s.replace(/['"\s,]/g, '');
    if (!fs.existsSync(target) || normalize(fs.readFileSync(target, 'utf8')) !== normalize(content)) {
      throw new Error('Stale shared asset mapping: ' + file);
    }
  } else fs.writeFileSync(target, content);
}
for (const [asset, canonical] of Object.entries(manifest)) {
  if (!fs.existsSync(path.join(root, canonical))) throw new Error('Missing canonical asset: ' + canonical);
  // This also catches question/artwork tools accidentally updating only one copy.
  if (fs.existsSync(path.join(root, asset))) {
    const hash = file => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
    if (hash(asset) !== hash(canonical)) throw new Error('Shared source differs: ' + asset);
  }
}
console.log(`Validated ${Object.keys(manifest).length} shared asset routes.`);
