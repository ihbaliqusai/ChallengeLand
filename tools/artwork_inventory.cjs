const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

function dimensions(file) {
  const b = fs.readFileSync(file);
  if (b.toString('ascii', 1, 4) === 'PNG') return [b.readUInt32BE(16), b.readUInt32BE(20)];
  if (b.toString('ascii', 0, 4) === 'RIFF') {
    for (let p = 12; p + 8 < b.length;) {
      const tag = b.toString('ascii', p, p + 4), n = b.readUInt32LE(p + 4), d = p + 8;
      if (tag === 'VP8X') return [b.readUIntLE(d + 4, 3) + 1, b.readUIntLE(d + 7, 3) + 1];
      if (tag === 'VP8L') { const bits = b.readUInt32LE(d + 1); return [(bits & 16383) + 1, ((bits >>> 14) & 16383) + 1]; }
      if (tag === 'VP8 ') return [b.readUInt16LE(d + 6) & 16383, b.readUInt16LE(d + 8) & 16383];
      p += 8 + n + (n & 1);
    }
  }
  if (b[0] === 255 && b[1] === 216) {
    let p = 2;
    while (p + 8 < b.length) {
      if (b[p++] !== 255) continue;
      const marker = b[p++];
      if (marker === 255 || marker === 0) continue;
      if (marker === 217 || marker === 218) break;
      const size = b.readUInt16BE(p);
      if ([192, 193, 194, 195, 197, 198, 199, 201, 202, 203, 205, 206, 207].includes(marker)) {
        return [b.readUInt16BE(p + 5), b.readUInt16BE(p + 3)];
      }
      p += size;
    }
  }
  throw new Error('Unsupported artwork: ' + file);
}

function shippedAssets() {
  const yaml = fs.readFileSync(path.join(root, 'pubspec.yaml'), 'utf8');
  const assets = new Set();
  for (const match of yaml.matchAll(/^\s+-\s+(?:asset:\s+)?(assets\/[^\r\n]+)$/gm)) {
    const asset = match[1].trim();
    if (asset.endsWith('/')) {
      for (const file of fs.readdirSync(path.join(root, asset), {withFileTypes: true})) {
        if (file.isFile()) assets.add(asset + file.name);
      }
    } else assets.add(asset);
  }
  return [...assets];
}

function writeRegistry() {
  const shared = JSON.parse(fs.readFileSync(path.join(__dirname, 'shared_assets.json'), 'utf8'));
  const rows = [...new Set([...shippedAssets(), ...Object.keys(shared)])]
    .filter(file => /\.(png|webp|jpe?g|jfif)$/i.test(file)).sort().map(file => {
      const size = dimensions(path.join(root, shared[file] || file));
      return `  ${JSON.stringify(file)}: Size(${size[0]}, ${size[1]}),`;
    });
  fs.writeFileSync(path.join(root, 'lib/core/artwork_sizes.g.dart'),
    `// Generated by tools/artwork_inventory.cjs.\nimport 'dart:ui';\n\nconst artworkSizes = <String, Size>{\n${rows.join('\n')}\n};\n`);
  console.log(`Indexed ${rows.length} image dimensions.`);
}

module.exports = {root, dimensions, shippedAssets};
if (require.main === module) writeRegistry();
