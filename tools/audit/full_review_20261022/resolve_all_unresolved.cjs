"use strict";
const fs = require("node:fs");
const path = require("node:path");

const entPath = path.join(__dirname, "entertainment", "review.json");
const sciPath = path.join(__dirname, "science", "review.json");

const ent = JSON.parse(fs.readFileSync(entPath, "utf8"));
const sci = JSON.parse(fs.readFileSync(sciPath, "utf8"));

const entEdits = new Map(ent.edits.map(e => [e.index, e]));
const sciEdits = new Map(sci.edits.map(e => [e.index, e]));

function editEnt(index, changes, reason, kind = "correction") {
  const existing = entEdits.get(index);
  entEdits.set(index, {
    index,
    changes: { ...(existing?.changes || {}), ...changes },
    reason: [existing?.reason, reason].filter(Boolean).join("؛ "),
    kind: existing?.kind === "replacement" ? "replacement" : kind,
    sources: existing?.sources || []
  });
}

function editSci(index, changes, reason, kind = "correction") {
  const existing = sciEdits.get(index);
  sciEdits.set(index, {
    index,
    changes: { ...(existing?.changes || {}), ...changes },
    reason: [existing?.reason, reason].filter(Boolean).join("؛ "),
    kind: existing?.kind === "replacement" ? "replacement" : kind,
    sources: existing?.sources || []
  });
}

